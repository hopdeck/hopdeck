# Starts the panel (pnpm dev) with the test VMs of several systems at once:
# those named, or else every one dev/vm-host/up.sh has started. Start them
# first with dev/vm-host/up.sh SYSTEM.
#
#   dev/vm-host/panel.sh [SYSTEM...]
#
# Each account of each VM appears as "VM SYSTEM: account"; its SSH alias is
# hopdeck-vm-SYSTEM-ACCOUNT. The combined ssh config and hosts.json are
# written to .dev/vm-host/panel. The panel takes the first free ports from
# 7400 and 5173, so one already running stays as it is.
set -eu

here=$(cd "$(dirname "$0")" && pwd)
repo=$(cd "$here/../.." && pwd)
state="$repo/.dev/vm-host"
keys="$repo/.dev/test-host"
panel="$state/panel"

[ "${1:-}" != -- ] || shift
if [ "$#" -eq 0 ]; then
	for described in "$state"/*/host.json; do
		[ -f "$described" ] || continue
		set -- "$@" "$(basename "$(dirname "$described")")"
	done
fi
if [ "$#" -eq 0 ]; then
	echo "no test VM has been started; start one with dev/vm-host/up.sh SYSTEM" >&2
	exit 1
fi

label() {
	case "$1" in
	root) echo 'root' ;;
	admin) echo 'sudo with password' ;;
	nopass) echo 'sudo without password' ;;
	plain) echo 'no sudo' ;;
	esac
}

mkdir -p "$panel/config"
ssh_config="$panel/ssh_config"
hosts=""
echo "# Generated by dev/vm-host/panel.sh" >"$ssh_config"
for system in "$@"; do
	described="$state/$system/host.json"
	if [ ! -f "$described" ]; then
		echo "$system has not been started; run dev/vm-host/up.sh $system" >&2
		exit 1
	fi
	address=$(sed -n 's/.*"address": "\([^"]*\)".*/\1/p' "$described")
	accounts=$(sed -n 's/.*"accounts": \[\([^]]*\)\].*/\1/p' "$described" | tr -d '",')
	for account in $accounts; do
		printf 'Host hopdeck-vm-%s-%s\n\tUser %s\n\tHostName %s\n\tIdentityFile "%s"\n\tIdentitiesOnly yes\n\tUserKnownHostsFile "%s"\n\tStrictHostKeyChecking yes\n' \
			"$system" "$account" "$account" "$address" "$keys/id_ed25519" "$state/$system/known_hosts" >>"$ssh_config"
		hosts="$hosts    { \"id\": \"vm-$system-$account\", \"destination\": \"hopdeck-vm-$system-$account\", \"name\": \"VM $system: $(label "$account")\" },\n"
	done
done
printf '{\n  "version": 1,\n  "hosts": [\n%b' "$hosts" | sed '$ s/},$/}/' >"$panel/config/hosts.json"
printf '  ]\n}\n' >>"$panel/config/hosts.json"

echo "Starting the panel with the VMs: $*"
cd "$repo"
# Keys generated in the panel go to .dev/test-host/generated-keys, not ~/.ssh,
# and hopdeck's own agent holds them, not the session's.
exec env -u SSH_AUTH_SOCK HOPDECK_CONFIG_DIR="$panel/config" HOPDECK_SSH_CONFIG="$ssh_config" HOPDECK_SSH_DIR="$keys/generated-keys" pnpm dev
