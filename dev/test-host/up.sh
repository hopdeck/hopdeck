#!/bin/sh
# Starts a Debian 13 container that plays a remote firewall for nftm, with
# systemd, sshd, nftables and one account per privilege case. Its nftables
# ruleset lives in the container's own network namespace, never the real one.
#
# Everything it generates (test key, known_hosts, ssh config, nftm config)
# stays in .dev/test-host, which git ignores; ~/.ssh is never touched. Then:
#
#   pnpm dev:test-host
set -eu

here=$(cd "$(dirname "$0")" && pwd)
repo=$(cd "$here/../.." && pwd)
state="$repo/.dev/test-host"
name=nftm-test-host
port=${NFTM_TEST_PORT:-2222}

mkdir -p "$state/config"
[ -f "$state/id_ed25519" ] || ssh-keygen -q -t ed25519 -N '' -C nftm-test -f "$state/id_ed25519"
# A key the host does not have, to fake a changed host key.
[ -f "$state/other_host_key" ] || ssh-keygen -q -t ed25519 -N '' -C nftm-test-other -f "$state/other_host_key"

echo "Building the image (the first time takes a minute)..."
podman build -q -t "$name" "$here" >/dev/null
podman rm -f "$name" >/dev/null 2>&1 || true
podman run -d --name "$name" \
	--cap-add NET_ADMIN \
	-p "127.0.0.1:$port:22" \
	-v "$state/id_ed25519.pub:/etc/ssh/nftm_authorized_keys:ro" \
	"$name" >/dev/null

# Until boot finishes, /run/nologin keeps everyone but root out.
i=0
until boot=$(podman exec "$name" systemctl is-system-running 2>/dev/null); [ "$boot" = running ] || [ "$boot" = degraded ]; do
	i=$((i + 1))
	if [ "$i" -ge 60 ]; then
		echo "the container did not finish booting (state: ${boot:-unknown}); see: podman logs $name" >&2
		exit 1
	fi
	sleep 1
done

i=0
until ssh-keyscan -T 2 -p "$port" 127.0.0.1 >"$state/known_hosts" 2>/dev/null && [ -s "$state/known_hosts" ]; do
	i=$((i + 1))
	if [ "$i" -ge 30 ]; then
		echo "sshd did not come up; see: podman logs $name" >&2
		exit 1
	fi
	sleep 1
done
printf '[127.0.0.1]:%s %s\n' "$port" "$(cut -d' ' -f1,2 "$state/other_host_key.pub")" >"$state/known_hosts.changed"

# ssh uses the first value it finds, so specific hosts come before the wildcard.
cat >"$state/ssh_config" <<CONFIG
# Generated by dev/test-host/up.sh
Host nftm-test-root
	User root
Host nftm-test-admin
	User admin
Host nftm-test-nopass
	User nopass
Host nftm-test-plain
	User plain
Host nftm-test-unknown-key
	User root
	UserKnownHostsFile /dev/null
Host nftm-test-changed-key
	User root
	UserKnownHostsFile "$state/known_hosts.changed"
Host nftm-test-*
	HostName 127.0.0.1
	Port $port
	IdentityFile "$state/id_ed25519"
	IdentitiesOnly yes
	UserKnownHostsFile "$state/known_hosts"
	StrictHostKeyChecking yes
CONFIG

cat >"$state/config/hosts.json" <<HOSTS
{
  "version": 1,
  "hosts": [
    { "id": "test-root", "destination": "nftm-test-root", "name": "Test: root" },
    { "id": "test-admin", "destination": "nftm-test-admin", "name": "Test: sudo with password" },
    { "id": "test-nopass", "destination": "nftm-test-nopass", "name": "Test: sudo without password" },
    { "id": "test-plain", "destination": "nftm-test-plain", "name": "Test: no sudo" },
    { "id": "test-unknown-key", "destination": "nftm-test-unknown-key", "name": "Test: unknown host key" },
    { "id": "test-changed-key", "destination": "nftm-test-changed-key", "name": "Test: changed host key" }
  ]
}
HOSTS

cat <<DONE
Test host is up: Debian 13 in container $name, ssh on 127.0.0.1:$port.
  Start nftm against it:  pnpm dev:test-host
  Log in by hand:         ssh -F .dev/test-host/ssh_config nftm-test-root
  Stop it:                dev/test-host/down.sh
Accounts: root; admin (sudo, password nftm-test); nopass (sudo for nft without a password); plain (password nftm-test, no sudo).
DONE
