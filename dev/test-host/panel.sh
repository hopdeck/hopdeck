# Starts the panel (pnpm dev) with the test hosts of several systems at once:
# those named, or else every one whose container is running. Start them first
# with dev/test-host/up.sh SYSTEM.
#
#   dev/test-host/panel.sh [SYSTEM...]
#
# Each host appears as "SYSTEM: account"; its SSH alias is hopdeck-SYSTEM-ACCOUNT.
# The combined ssh config and hosts.json are written to .dev/test-host/panel.
set -eu

here=$(cd "$(dirname "$0")" && pwd)
repo=$(cd "$here/../.." && pwd)
keys="$repo/.dev/test-host"
panel="$keys/panel"

[ "${1:-}" != -- ] || shift
if [ "$#" -eq 0 ]; then
	set -- $(podman ps --format '{{.Names}}' | sed -n 's/^hopdeck-test-//p' | sort)
fi
if [ "$#" -eq 0 ]; then
	echo "no test host is running; start one with dev/test-host/up.sh SYSTEM" >&2
	exit 1
fi

label() {
	case "$1" in
	root) echo 'root' ;;
	admin) echo 'sudo with password' ;;
	nopass) echo 'sudo without password' ;;
	plain) echo 'no sudo' ;;
	esac
}

mkdir -p "$panel/config"
ssh_config="$panel/ssh_config"
hosts=""
echo "# Generated by dev/test-host/panel.sh" >"$ssh_config"
for system in "$@"; do
	described="$keys/$system/host.json"
	if [ ! -f "$described" ]; then
		echo "$system has not been started; run dev/test-host/up.sh $system" >&2
		exit 1
	fi
	port=$(sed -n 's/.*"port": \([0-9]*\).*/\1/p' "$described")
	accounts=$(sed -n 's/.*"accounts": \[\(.*\)\].*/\1/p' "$described" | tr -d '",')
	for account in $accounts; do
		printf 'Host hopdeck-%s-%s\n\tUser %s\n\tHostName 127.0.0.1\n\tPort %s\n\tIdentityFile "%s"\n\tIdentitiesOnly yes\n\tUserKnownHostsFile "%s"\n\tStrictHostKeyChecking yes\n' \
			"$system" "$account" "$account" "$port" "$keys/id_ed25519" "$keys/$system/known_hosts" >>"$ssh_config"
		hosts="$hosts    { \"id\": \"$system-$account\", \"destination\": \"hopdeck-$system-$account\", \"name\": \"$system: $(label "$account")\" },\n"
	done
	# As in up.sh: an account no key opens yet, for the key setup; OpenWrt has root only.
	nokey=admin
	case " $accounts " in *" admin "*) ;; *) nokey=root ;; esac
	printf 'Host hopdeck-%s-nokey\n\tUser %s\n\tHostName 127.0.0.1\n\tPort %s\n\tIdentityFile "%s"\n\tIdentitiesOnly yes\n\tUserKnownHostsFile "%s"\n\tStrictHostKeyChecking yes\n' \
		"$system" "$nokey" "$port" "$keys/$system/no-key-yet" "$keys/$system/known_hosts" >>"$ssh_config"
	hosts="$hosts    { \"id\": \"$system-nokey\", \"destination\": \"hopdeck-$system-nokey\", \"name\": \"$system: no key yet ($nokey, password hopdeck-test)\" },\n"
done
printf '{\n  "version": 1,\n  "hosts": [\n%b' "$hosts" | sed '$ s/},$/}/' >"$panel/config/hosts.json"
printf '  ]\n}\n' >>"$panel/config/hosts.json"

echo "Starting the panel with: $*"
cd "$repo"
# Keys generated in the panel go to .dev/test-host/generated-keys, not ~/.ssh,
# and hopdeck's own agent holds them, not the session's.
exec env -u SSH_AUTH_SOCK HOPDECK_CONFIG_DIR="$panel/config" HOPDECK_SSH_CONFIG="$ssh_config" HOPDECK_SSH_DIR="$keys/generated-keys" pnpm dev
